// 背景：你有一组斯帕赛道的圈速数据（单位：秒）。
// 要求：
// 1. 定义一个数组 int laps[] = {145, 142, 140, 138, 139};（假设跑错了一圈，圈速变慢了）。
// 2. 定义一个指针 int *p = laps;（指向数组首地址）。
// 3. 必须使用指针运算（不能写 laps[i]），用一个 for 循环，把数组里的圈速全部打印出来。
#include <iostream>
int main()
{
	int laps[]{145, 142, 140, 138, 139};
	int * p = laps;
	for(int i = 1; i <= 5; i++)
	{
		std::cout << "第" << i << "个" << * p << std::endl;
		p++;
	}    
	return 0;
}
