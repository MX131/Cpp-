// 背景：赛会发现你第4圈（下标为3）的成绩被传感器记录错了，应该是 135 秒。
// 要求：
// 1. 继续使用上一题的数组和指针。
// 2. 利用指针，把数组中下标为 3 的元素，直接修改为 135。
// 3. 打印修改后的所有圈速。
#include <iostream>
int main()
{
	int laps[]{145, 142, 140, 138, 139};
	int * p = laps;
	*(p + 3) = 135;
	for(int i = 1; i <= 5; i++)
	{
		std::cout << "第" << i << "个" << * p << std::endl;
		p++;
	}    
	
	return 0;
}
