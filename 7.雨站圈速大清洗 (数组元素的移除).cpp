/*【背景】
MX131 在斯帕赛道进行雨战模拟，因为雨太大，传感器记录了一堆圈速。但由于天气影响，有些圈速慢得离谱（比如跑出 300 秒以上），这些属于无效圈速，必须从记录中剔除。
【输入要求】
1. 第一行输入一个整数 N（表示一共记录了 N 个圈速，比如 N = 8）。
2. 第二行输入 N 个整数，代表具体的圈速（例如：145 310 140 280 138 305 139 142）。
(注意：因为 N 是运行时才输入的，所以你必须用 new 来动态申请这个数组！)
【核心处理逻辑（难点）】
3. 剔除所有大于 250 秒的圈速（无效圈速）。
4. 绝对不能用“新建一个数组”的方法，必须像刚才学的那样，使用“双指针（读写指针）原地覆盖法”，把有效的圈速死死挤到原数组的最前面。
【输出要求】
5. 第一行输出处理后的有效圈速（用指针运算 *(pArr + i) 遍历输出，空格隔开）。
6. 第二行输出处理后剩余的有效圈速总个数。
7. 最后，务必用最安全的方式（delete[] + nullptr）释放内存！
---
【样例演示】
输入：
```text
8
145 310 140 280 138 305 139 142
```
输出：
```text
145 140 138 139 142
5
```
(解释：310、280、305 被剔除了，剩下5个有效圈速) */
#include <iostream>
using std::cout;
using std::endl;
int main()
{
	int n = 8;
	int j = 0;
	int *N = new int[8]{145,310,140,280,138,305,139,142};
	for(int i = 0; i < 8; i++)
	{
		if(N[i] > 250)
		{
			n--;
			continue;
		}
		N[j] = N[i];
		j++;
		cout << N[i] << " ";
	}
	cout << "\n" << n;
	delete[] N;
	N = nullptr;
	return 0;
}
